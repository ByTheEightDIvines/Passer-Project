"""routes.json + camps.json -> src/travel_network_data.inc (plain C++ tables).

Points carry their stage and room (from the collision grid), so the mod knows which loaded room a
traveller is in. Hand-off edges (loading screens) list the first stage's leg, then the second's.
"""
import sys, json, pickle, math
sys.path.insert(0, '/home/claude/anim/field')
from navgrid import Grid, CELL

R = json.load(open('/home/claude/anim/field/routes.json'))
C = {c['i']: c for c in json.load(open('/home/claude/anim/field/camps.json'))}
G = {st: pickle.load(open('/home/claude/anim/field/grid_%s.pkl' % st, 'rb')) for st in ('F_SP121', 'F_SP122')}
STAGES = ['F_SP121', 'F_SP122']
KIND = {'road': 0, 'camp': 1, 'beedle_tent': 2, 'gate': 3, 'broken_bridge': 4, 'bridge_east': 5}
F_ESCORT, F_NEEDS_BRIDGE, F_NO_BEEDLE, F_HANDOFF, F_SPUR = 1, 2, 4, 8, 16

nodes = {int(k): v for k, v in R['nodes'].items()}
ids = sorted(nodes)
index = {n: i for i, n in enumerate(ids)}


def room_at(st, x, z, fallback):
    g = G[st]; i, j = g.cell(x, z)
    best = None
    for r in range(0, 6):
        for a in range(i - r, i + r + 1):
            for b in range(j - r, j + r + 1):
                if 0 <= a < g.nz and 0 <= b < g.nx and g.room[a, b] >= 0:
                    return int(g.room[a, b])
    return fallback


def node_pos(n):
    if n['kind'] in ('camp', 'beedle_tent') and n['i'] in C:
        p = C[n['i']]['placed']
        return p['x'], p['y'], p['z']
    return n['x'], n['y'], n['z']


points, edges = [], []
for e in R['edges']:
    A, B = nodes[e['a']], nodes[e['b']]
    flags = 0
    if e['kind'] == 'escort' or e.get('escort_only'):
        flags |= F_ESCORT
    if e.get('requires'):
        flags |= F_NEEDS_BRIDGE
    if e.get('no_beedle'):
        flags |= F_NO_BEEDLE
    if e['kind'] == 'spur':
        flags |= F_SPUR
    first = len(points)
    split = 0
    if e['kind'] == 'handoff':
        flags |= F_HANDOFF
        seq = [(A['stage'], p) for p in [(A['x'], A['z'], A['y'])] + [(p[0], p[1], p[2]) for p in e['leg_a']]]
        split = len(seq)
        seq += [(B['stage'], p) for p in [(p[0], p[1], p[2]) for p in e['leg_b']] + [(B['x'], B['z'], B['y'])]]
    else:
        pts = e['points']
        ax, ay, az = node_pos(A); bx, by, bz = node_pos(B)
        pts = [(ax, az, ay)] + [tuple(p) for p in pts[1:-1]] + [(bx, bz, by)]
        seq = [(A['stage'], p) for p in pts]
    last_room = A['room']
    L = 0.0; prev = None
    for st, (x, z, y) in seq:
        room = room_at(st, x, z, last_room); last_room = room
        if prev is not None and prev[0] == st:
            L += math.hypot(x - prev[1], z - prev[2])
        points.append((STAGES.index(st), room, x, y, z))
        prev = (st, x, z)
    edges.append((index[e['a']], index[e['b']], flags, first, len(points) - first, split, L))

out = ['// Generated by tools/field/export_network.py from data/routes.json + data/camps.json. Do not edit.',
       '#pragma once', '', 'namespace travel_data {', '',
       'constexpr const char* kStages[] = {"F_SP121", "F_SP122"};', '']
out.append('// kind: 0 road, 1 camp, 2 Beedle\'s tent, 3 Castle Town gate, 4 broken bridge end, 5 bridge east end')
out.append('struct Node { unsigned char stage; signed char room; unsigned char kind; float x, y, z; unsigned short facing; };')
out.append('constexpr Node kNodes[] = {')
for n in ids:
    v = nodes[n]
    kind = 'gate' if v.get('gate') else v['kind']
    x, y, z = node_pos(v)
    room = room_at(v['stage'], x, z, v['room'])
    out.append('    {%d, %d, %d, %.1ff, %.1ff, %.1ff, %d},  // spot %d' % (STAGES.index(v['stage']), room, KIND[kind], x, y, z, int(v.get('ang', 0)) & 0xFFFF, n))
out.append('};')
out.append('')
out.append('// flags: 1 escort only, 2 needs the Eldin-side bridge repaired, 4 no Beedle, 8 loading-screen hand-off, 16 camp spur')
out.append('struct Edge { unsigned short a, b; unsigned char flags; unsigned short first, count, split; float length; };')
out.append('constexpr Edge kEdges[] = {')
for a, b, f, first, cnt, split, L in edges:
    out.append('    {%d, %d, %d, %d, %d, %d, %.1ff},' % (a, b, f, first, cnt, split, L))
out.append('};')
out.append('')
out.append('struct Point { unsigned char stage; signed char room; float x, y, z; };')
out.append('constexpr Point kPoints[] = {')
for st, room, x, y, z in points:
    out.append('    {%d, %d, %.1ff, %.1ff, %.1ff},' % (st, room, x, y, z))
out.append('};')
out.append('')
out.append('// Ground probe for the repaired bridge (middle of the Eldin-side span)')
out.append('constexpr float kBridgeProbe[3] = {34697.0f, -299.0f, -26595.0f};')
out.append('')
# camps with fitted ground
out.append('struct Camp { unsigned short node; float x, y, z; unsigned short facing; float clearRadius, tiltDeg, slopeX, slopeZ; };')
out.append('constexpr Camp kCamps[] = {')
for n in ids:
    v = nodes[n]
    if v['kind'] in ('camp', 'beedle_tent') and n in C:
        p = C[n]['placed']
        out.append('    {%d, %.1ff, %.1ff, %.1ff, %d, %.1ff, %.1ff, %.5ff, %.5ff},  // %s spot %d' % (
            index[n], p['x'], p['y'], p['z'], int(v['ang']) & 0xFFFF, p['clear_radius'], p['tilt_deg'],
            p['slope_dir'][0], p['slope_dir'][1], v['kind'], n))
out.append('};')
out.append('')
out.append('}  // namespace travel_data')
open(sys.argv[1] if len(sys.argv) > 1 else '/home/claude/passer-project/src/travel_network_data.inc', 'w').write('\n'.join(out) + '\n')
print(len(ids), 'nodes', len(edges), 'edges', len(points), 'points')
