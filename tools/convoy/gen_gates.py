"""Bake the convoys' stretches outside Castle Town (F_SP122) into src/convoy_gates.inc.
east (room 17): the field's loading zone -> along the east bridge -> Castle Town's east gate
west (room 8):  Castle Town's west gate -> over the west bridge -> the field's loading zone
Same world coordinates as Hyrule Field (F_SP121). Run with python3 -I gen_gates.py."""
import sys, pickle, numpy as np
sys.path[:0] = ['/home/claude/passer-project/tools/field', '/home/claude/anim/field']
import navgrid, __main__; __main__.Grid = navgrid.Grid
import routes; routes.HARD_STEP = 160
from routes import astar
g = pickle.load(open('/home/claude/anim/field/grid_F_SP122.pkl', 'rb'))
def snapc(x, z):
    i, j = g.cell(x, z)
    for k in range(0, 40):
        sub = g.walk[max(0, i - k):i + k + 1, max(0, j - k):j + k + 1]
        if sub.any():
            a, b = np.argwhere(sub)[len(np.argwhere(sub)) // 2]; return (max(0, i - k) + a, max(0, j - k) + b)
def dense(pts, step=150.0):
    pts = np.asarray(pts, float); out = [pts[0]]
    for a, b in zip(pts[:-1], pts[1:]):
        n = max(1, int(np.hypot(*(b - a)) // step))
        for k in range(1, n + 1): out.append(a + (b - a) * k / n)
    return np.array(out)
def smooth(p, it=4):
    p = p.copy()
    for _ in range(it): p[1:-1] = 0.25 * p[:-2] + 0.5 * p[1:-1] + 0.25 * p[2:]
    return p
def bake(a, b, room):
    p = astar(g, snapc(*a), snapc(*b), margin=300)
    pts = smooth(dense([a] + [g.world(*c) for c in p] + [b])); ys = []; prev = None
    for x, z in pts:
        i, j = g.cell(x, z); h = g.h[i - 2:i + 3, j - 2:j + 3]; h = h[h > -1e8]
        if not h.size: ys.append(np.nan); continue
        y = float(h[np.argmin(np.abs(h - prev))]) if prev is not None else float(np.median(h))
        ys.append(y); prev = y
    ys = np.array(ys); ok = ~np.isnan(ys)
    ys = np.interp(np.arange(len(ys)), np.where(ok)[0], ys[ok])
    ys = np.array([np.median(ys[max(0, i - 3):i + 4]) for i in range(len(ys))])
    return [(float(x), float(y), float(z), room) for (x, z), y in zip(pts, ys)]
east = bake((-32803.0, 8704.7), (-45250.0, 10667.0), 17)   # starts where the field road ends
west = bake((-59900.0, 10622.0), (-85903.0, 4204.7), 8)    # ends where the field's west road starts
out = ['// Generated by tools/convoy/gen_gates.py: the convoys outside Castle Town (F_SP122).',
       '// Points every ~150 units: x, y (ground), z, room. Same coordinates as the field.']
for name, pts in (('kEastGate', east), ('kWestGate', west)):
    out.append(f'const ConvoyPt {name}[] = {{')
    out += [f'    {{{x:.1f}f, {y:.1f}f, {z:.1f}f, {r}}},' for x, y, z, r in pts]
    out.append('};')
open('/home/claude/passer-project/src/convoy_gates.inc', 'w').write('\n'.join(out) + '\n')
for n, p in (('east', east), ('west', west)):
    ys = [q[1] for q in p]; print(n, len(p), round(min(ys)), round(max(ys)), p[0][:3], p[-1][:3])
