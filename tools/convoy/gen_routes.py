"""Bake the three convoy roads into src/convoy_routes.inc: points every ~150 units with ground height and room.
gorge: Faron Woods -> Kakariko Gorge -> east field -> Castle Town east loading zone (the early-story road)
long:  Faron Woods -> west canyon -> north field -> north canyon -> Eldin bridge -> Castle Town east (royal runs it backwards)
west:  Castle Town west exit -> the long road below it -> west canyon -> Faron Woods
Run with python3 -I gen_routes.py (needs the field grid and rooms pickles under /home/claude/anim/field)."""
import sys, json, pickle, numpy as np
sys.path[:0] = ['/home/claude/passer-project/tools/field', '/home/claude/anim/field']
import navgrid, __main__; __main__.Grid = navgrid.Grid
import routes; routes.HARD_STEP = 160
from routes import astar
from scipy.spatial import cKDTree
g = pickle.load(open('/home/claude/anim/field/grid_F_SP121.pkl', 'rb'))
rooms = pickle.load(open('/home/claude/anim/field/rooms.pkl', 'rb'))
C = []; L = []
for (st, rn), v in rooms.items():
    if st == 'F_SP121': C.append(v['T'].mean(1)[:, [0, 2]]); L += [rn] * len(v['T'])
tree = cKDTree(np.concatenate(C)); L = np.array(L)
R = json.load(open('/home/claude/h2/DT_handover_2026-11-17_2/session_2026-11-17/work/convoy_route.json'))
route = np.array(R['route'])[:, [0, 2]]
alt = json.load(open('/home/claude/blockers/alt.json'))
def snapc(x, z):
    i, j = g.cell(x, z)
    for k in range(1, 40):
        sub = g.walk[i - k:i + k + 1, j - k:j + k + 1]
        if sub.any():
            a, b = np.argwhere(sub)[len(np.argwhere(sub)) // 2]; return (i - k + a, j - k + b)
def path(a, b):
    p = astar(g, snapc(*a), snapc(*b), margin=300)
    return [g.world(*c) for c in p]
def dense(pts, step=150.0):
    pts = np.asarray(pts, float); out = [pts[0]]
    for a, b in zip(pts[:-1], pts[1:]):
        n = max(1, int(np.hypot(*(b - a)) // step))
        for k in range(1, n + 1): out.append(a + (b - a) * k / n)
    return np.array(out)
def smooth(p, it=3):
    p = p.copy()
    for _ in range(it): p[1:-1] = 0.25 * p[:-2] + 0.5 * p[1:-1] + 0.25 * p[2:]
    return p
def bake(pts):
    pts = smooth(dense(pts)); ys = []; prev = None
    for x, z in pts:
        i, j = g.cell(x, z); h = g.h[i - 2:i + 3, j - 2:j + 3]; h = h[h > -1e8]
        if not h.size: ys.append(np.nan); continue
        y = float(h[np.argmin(np.abs(h - prev))]) if prev is not None else float(np.median(h))
        ys.append(y); prev = y   # the surface that carries on from the last point (not a cliff top beside it)
    ys = np.array(ys); ok = ~np.isnan(ys)
    ys = np.interp(np.arange(len(ys)), np.where(ok)[0], ys[ok])   # gaps (the bridges): straight across
    ys = np.array([np.median(ys[max(0, i - 3):i + 4]) for i in range(len(ys))])   # no one-point spikes (a ledge picked up)
    rm = L[tree.query(pts)[1]]
    return [(float(x), float(y), float(z), int(r)) for (x, z), y, r in zip(pts, ys, rm)]
gorge = bake(list(alt[0]) + list(alt[1]) + [tuple(p) for p in route[855:]])
long_ = bake(route)
wexit = (-85855.0, 4220.0)
k = int(np.hypot(*(route - np.array(wexit)).T).argmin())
west = bake(path(wexit, tuple(route[k])) + [tuple(p) for p in route[k::-1]])
out = ['// Generated by tools/convoy/gen_routes.py: the convoy roads in Hyrule Field (F_SP121).',
       '// Points every ~150 units: x, y (ground), z, room.',
       'struct ConvoyPt { float x, y, z; signed char room; };']
for name, pts in (('kGorgeRoad', gorge), ('kLongRoad', long_), ('kWestRoad', west)):
    out.append('constexpr ConvoyPt %s[] = {' % name)
    out += ['    {%.1ff, %.1ff, %.1ff, %d},' % p for p in pts]
    out.append('};')
open('/home/claude/passer-project/src/convoy_routes.inc', 'w').write('\n'.join(out) + '\n')
print('gorge', len(gorge), 'long', len(long_), 'west', len(west), 'join index', k)
